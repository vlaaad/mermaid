"""Shared whale geometry and sparse, world-fixed cruising routes."""
import math,json
from pathlib import Path

WHALES=[
    dict(id='whale_0',center=[-30,38,-145],radius=[24,12],height=1.1,phase=math.pi/2,rate=.045,scale=3.8),
    dict(id='whale_1',center=[90,34,-165],radius=[26,15],height=1.5,phase=2.2,rate=-.032,scale=4.2),
    dict(id='whale_2',center=[-96,-38,60],radius=[22,16],height=2.0,phase=1.0,rate=.028,scale=3.6),
]

def whale(Mesh):
    """A smooth baleen-whale silhouette: broad head, throat, long fins, flukes."""
    import numpy as np
    m=Mesh();sides=24
    # z, center y, half width, half height: face forward along -Z.
    sections=[(-3.65,.02,.12,.12),(-3.45,.02,.62,.45),(-3.05,.04,.94,.72),
              (-2.4,.10,1.08,.90),(-1.5,.13,1.12,1.0),(-.4,.15,1.0,.95),
              (.8,.18,.83,.78),(1.9,.20,.60,.57),(2.9,.20,.36,.36),
              (3.7,.17,.20,.22),(4.35,.12,.16,.13),(4.65,.10,.18,.09)]
    def vertex(i,j):
        z,y,w,h=sections[i];a=j*math.tau/sides
        p=np.array([w*math.cos(a),y+h*math.sin(a),z])
        prev=sections[max(0,i-1)];nxt=sections[min(len(sections)-1,i+1)]
        tangent=np.array([(nxt[2]-prev[2])*math.cos(a),nxt[1]-prev[1]+(nxt[3]-prev[3])*math.sin(a),nxt[0]-prev[0]])
        across=np.array([-w*math.sin(a),h*math.cos(a),0]);n=np.cross(across,tangent);n/=np.linalg.norm(n)
        belly=max(0,-math.sin(a))**3
        color=tuple(v*(1-belly)+b*belly for v,b in zip((.055,.105,.14),(.12,.19,.23)))+(0,)
        return p,n,color
    for i in range(len(sections)-1):
        for j in range(sides):
            points=[vertex(i,j),vertex(i,j+1),vertex(i+1,j+1),vertex(i+1,j)]
            for ids in [[0,1,2],[0,2,3]]:
                q=[points[k] for k in ids];m.tri(*(v[0] for v in q),q[0][2],normals=[v[1] for v in q])
    for i,sign in [(0,-1),(len(sections)-1,1)]:
        z,y,_,_=sections[i]
        for j in range(sides):
            a,b=vertex(i,j)[0],vertex(i,j+1)[0]
            if sign<0:a,b=b,a
            m.tri((0,y,z),a,b,(.06,.11,.15,0))
    def fin(points,widths,thickness,color):
        # Paired, tapered skins with smooth taper normals from the shared tube.
        m.tube(points,[(thickness*(1-i/(len(points)+.3)),w) for i,w in enumerate(widths)],color,10)
    for side in [-1,1]:
        fin([(side*.78,-.32,-1.6),(side*1.2,-.58,-1.35),(side*2.0,-.90,-.7),
             (side*2.8,-1.04,.20),(side*3.15,-1.0,.78)], [.32,.40,.34,.20,.015],.10,(.09,.16,.19,.5))
        # Horizontal flukes, with a central notch and swept tips.
        fin([(0,.10,4.50),(side*.60,.10,4.62),(side*1.25,.08,4.90),(side*1.9,.11,5.25),
             (side*2.22,.16,5.44)],[.26,.53,.48,.25,.015],.07,(.07,.13,.17,.75))
        m.ellipsoid((side*.89,-.04,-2.75),(.047,.047,.038),(.018,.045,.055,0),4,8)
        # A quiet jaw seam, geometry rather than extra textures.
        m.tube([(side*.10,-.14,-3.61),(side*.57,-.25,-3.38),(side*.83,-.40,-2.85)], [.012,.014,.009],(.09,.18,.21,0),6)
    # A small swept dorsal fin and two nostrils on the crown.
    fin([(0,.93,.55),(0,1.25,.95),(0,1.43,1.27)], [.24,.18,.015],.08,(.055,.105,.14,0))
    for x in [-.09,.09]:m.ellipsoid((x,.96,-1.75),(.035,.012,.07),(.06,.13,.16,0),3,8)
    return m

def export_routes(root):
    root=Path(root);objects=[];routes=[]
    for r in WHALES:
        x,y,z=r['center'];rx,rz=r['radius'];a=r['phase']
        p=[x+rx*math.cos(a),y+r['height']*math.sin(a*2),z+rz*math.sin(a)]
        objects.append('instances { id: "%s" prototype: "/assets/generated/whale.go" position {x:%f y:%f z:%f} rotation {w:1} scale3 {x:%f y:%f z:%f} }'%(r['id'],*p,*([r['scale']]*3)))
        routes.append('{id="/ocean/%s",asset="whale",center={%s},radius={%s},height=%s,phase=%s,rate=%s,scale=%s}'%(r['id'],','.join(map(str,r['center'])),','.join(map(str,r['radius'])),r['height'],r['phase'],r['rate'],r['scale']))
    (root/'main/ocean_animals.collection').write_text('name: "ocean_animals"\n'+'\n'.join(objects)+'\n')
    (root/'main/ocean_routes.lua').write_text('-- Generated by tools/sea_animals.py. Routes do not follow the camera.\nreturn {\n'+',\n'.join(routes)+'\n}\n')
    (root/'assets/source/whale-routes.json').write_text(json.dumps(WHALES,indent=2)+'\n')
